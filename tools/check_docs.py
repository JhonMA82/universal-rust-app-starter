#!/usr/bin/env python3
"""Check documentation links and derive the module catalog from its manifests."""
import argparse
from pathlib import Path
import re
import sys
import tomllib
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from generator.compose import catalog, composition_guide, read_json

LINK = re.compile(r"(?<!!)\[[^\]\n]+\]\(([^\s()]+)\)")


def links(file, root):
    for target in LINK.findall(file.read_text(encoding="utf-8")):
        if target.startswith(("#", "<", "/")) or urlsplit(target).scheme:
            continue
        path = unquote(urlsplit(target).path)
        if not path or "{{" in path:
            continue
        resolved = (file.parent / path).resolve()
        if not resolved.is_relative_to(root) or not resolved.exists():
            yield f"{file.relative_to(root)}: unresolved link {target}"


def module_table(modules, presets):
    result = ["# Module catalog", "", "Generated by `python3 tools/check_docs.py --write`.", "",
              "| Module | Targets | Profiles | Integration | Dependencies |",
              "| --- | --- | --- | --- | --- |"]
    for name, module in modules.items():
        path = f"../modules/{name}/files/{module['documentation']}"
        dependencies = ", ".join(dep.split("@")[0] for dep in module["dependencies"]) or "—"
        result.append(f"| [{name}]({path}) | {', '.join(module['targets'])} | "
                      f"{', '.join(module['profiles']) or 'All'} | {module['kind']} | {dependencies} |")
    result.extend(["", "## Presets", ""])
    for name, entries in presets.items():
        result.append(f"- **{name}** — {', '.join(entries) or 'Base profile'}")
    return "\n".join(result) + "\n"


def project_contract(root, report, modules):
    installed = report["modules"]
    if unknown := installed.keys() - modules.keys():
        yield f"unknown installed modules: {sorted(unknown)}"
        return
    guide = root / "docs/COMPOSITION.md"
    if installed:
        expected = composition_guide(
            report["profile"], report["preset"], report["entrypoints"],
            {name: modules[name] for name in installed},
        )
        if not guide.is_file() or guide.read_text(encoding="utf-8") != expected:
            yield "generated composition guide diverges from the selected entrypoints"
    elif guide.exists():
        yield "base profile advertises a modular composition guide"
    for name in installed:
        module = modules[name]
        for payload in module["files"]:
            if payload.startswith(("docs/", ".agents/skills/")) and not (root / payload).is_file():
                yield f"{name}: generated payload missing {payload}"


def inventory_errors(root, report):
    path = root / "infrastructure.json"
    if not path.is_file():
        yield "infrastructure inventory is missing"
        return
    inventory = read_json(path)
    for key in ("profile", "preset", "targets", "modules", "entrypoints", "capabilities"):
        if inventory.get(key) != report.get(key):
            yield f"infrastructure inventory differs from generation report for {key}"
    expected_skills = sorted(file.relative_to(root).as_posix() for file in (root / ".agents/skills").glob("*/SKILL.md"))
    if inventory["skills"] != expected_skills:
        yield "infrastructure inventory differs from installed skills"
    paths = [*inventory["skills"], *inventory["docs"], *inventory["product_sources"]]
    if inventory["visual_forge"]:
        paths.append(inventory["visual_forge"])
    for package in inventory["crates"].values():
        paths.append(package["manifest"])
        paths.extend(target["source"] for target in package["targets"])
    for filename in paths:
        resolved = (root / filename).resolve()
        if not resolved.is_relative_to(root) or not resolved.is_file():
            yield f"invalid inventory path: {filename}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate the module table")
    parser.add_argument("--project", type=Path, help="check one composed project")
    args = parser.parse_args()
    root = args.project.resolve() if args.project else ROOT
    errors = []
    if args.project:
        report = read_json(root / "generation-report.json")
        files = [root / "README.md", root / "AGENTS.md"]
        files.extend((root / "docs").rglob("*.md"))
        files.extend((root / ".agents/skills").rglob("*.md"))
        errors.extend(project_contract(root, report, catalog()))
        errors.extend(inventory_errors(root, report))
    else:
        modules = catalog()
        profiles = read_json(ROOT / "profiles.json")
        presets = read_json(ROOT / "presets/catalog.json")
        expected = module_table(modules, presets)
        table = ROOT / "docs/MODULE_CATALOG.md"
        if args.write:
            table.write_text(expected, encoding="utf-8")
        elif table.read_text(encoding="utf-8") != expected:
            errors.append("stale module table; run tools/check_docs.py --write")
        for name, data in modules.items():
            base = ROOT / "modules" / name / "files"
            if data["documentation"] not in data["files"]:
                errors.append(f"{name}: documentation missing from payload")
            if set(data["profiles"]) - set(profiles):
                errors.append(f"{name}: unknown profile")
            entries = {}
            features = []
            for file in sorted(data["files"]):
                if not file.endswith("/Cargo.toml"):
                    continue
                manifest = tomllib.loads((base / file).read_text(encoding="utf-8"))
                entries[file] = {key: value for key,value in manifest.items()
                                 if key in {"dependencies", "dev-dependencies", "build-dependencies", "target"}}
                if "package" in manifest:
                    features.extend(f"{manifest['package']['name']}/{f}" for f in manifest.get("features", {}))
            if entries != data["cargo_dependencies"] or sorted(features) != sorted(data["features"]):
                errors.append(f"{name}: Cargo metadata diverges from descriptor")
        for name, entries in presets.items():
            if set(entries) - set(modules):
                errors.append(f"{name}: unknown preset module")
        files = [root / "README.md", root / "AGENTS.md"]
        files.extend((root / "docs").rglob("*.md"))
        files.extend(root.glob("modules/*/files/docs/modules/*.md"))
    errors.extend(error for file in files for error in links(file, root))
    for error in errors:
        print(error, file=sys.stderr)
    if not errors:
        print(f"Documentation checks passed ({len(files)} files)")
    return int(bool(errors))


if __name__ == "__main__":
    sys.exit(main())
